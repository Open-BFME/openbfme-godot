// ONLINEMENU-1: writes src/disposable-domains.mjs from data/disposable-domains.txt (the Worker cannot read files; test/email-flow.test.mjs checks
// the two match). Run: node tools/gen-disposable-domains.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const text = readFileSync(join(root, 'data', 'disposable-domains.txt'), 'utf8');
const domains = text.split('\n').map((line) => line.trim()).filter((line) => line && !line.startsWith('#'));
if (domains.some((domain) => !/^[a-z0-9.-]+$/.test(domain))) throw new Error('unexpected characters in the disposable-domain list');
writeFileSync(join(root, 'src', 'disposable-domains.mjs'),
  '// Generated by tools/gen-disposable-domains.mjs from data/disposable-domains.txt (CC0, see data/DISPOSABLE-DOMAINS-SOURCE.md). Do not edit.\n' +
  `export const DISPOSABLE_DOMAINS = Object.freeze(${JSON.stringify(domains.join('\n'))}.split('\\n'));\n`);
console.log(`${domains.length} domains`);
