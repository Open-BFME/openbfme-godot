#!/usr/bin/env python3
"""Lane L10N-1: the OpenBFME text catalog (docs/L10N.md).

tools/l10n/catalog/<lang>.json is the one catalog of OpenBFME's own player-facing text (retail text keeps coming from the player's CSF
files). en.json is the source; every other file translates some of its ids. This tool validates the catalog, generates the
per-consumer data (the launcher's and the game's GDScript catalog, the engine's C++ table), reports translation coverage, checks
that every id the code uses exists (with the arguments its placeholders need), and lints the launcher's scripts for new
hard-coded English.

    python3 tools/l10n/l10n.py check          # catalog valid, generated files current, ids used == ids defined, lint clean
    python3 tools/l10n/l10n.py generate       # rewrite the generated files
    python3 tools/l10n/l10n.py coverage       # per language: translated / missing ids (missing ones show the English source)
    python3 tools/l10n/l10n.py lint [FILES]   # hard-coded English in launcher scripts (allow-list: tools/l10n/lint_allow.json)
    python3 tools/l10n/l10n.py add FILE.json  # merge new English ids (a flat {id: text} file) into en.json, then generate

Exit status 0 = clean; 1 = a problem (each printed on its own line).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CATALOG = REPO / "tools/l10n/catalog"
SOURCE = "en"
ALLOW = REPO / "tools/l10n/lint_allow.json"

ID = re.compile(r"[a-z][a-z0-9_]*(?:\.[a-z0-9_]+)+")
STATUSES = ("source", "complete", "partial", "sample")
# CLDR plural categories for whole numbers (the only counts OpenBFME text has); a language not listed here cannot be added
# until its rule is (all three runtimes implement the same table: l10n.gd plural_category, OpenBFMEText.cpp pluralCategory).
PLURAL_CATEGORIES = {
    "en": ("one", "other"), "de": ("one", "other"), "nl": ("one", "other"), "sv": ("one", "other"), "no": ("one", "other"),
    "it": ("one", "other"), "es": ("one", "other"), "hu": ("one", "other"), "fr": ("one", "other"), "pt": ("one", "other"),
    "pl": ("one", "few", "many"), "ru": ("one", "few", "many"), "cs": ("one", "few", "other"),
    "zh": ("other",), "ko": ("other",),
}

# Who gets which ids: each consumer's generated catalog holds its own prefix plus common.*.
CONSUMERS = {
    "launcher": (("launcher.", "common."), REPO / "launcher/scripts/l10n/catalog.gd"),
    "game": (("game.", "common."), REPO / "godot/scripts/l10n/catalog.gd"),
    "engine": (("engine.", "common."), REPO / "engine/src/GameClient/OpenBFMETextCatalog.inc"),
}
# The GDScript runtime is written once (the launcher's) and copied into the game project.
RUNTIME = REPO / "launcher/scripts/l10n/l10n.gd"
RUNTIME_COPY = REPO / "godot/scripts/l10n/l10n.gd"
GENERATED = "GENERATED by tools/l10n/l10n.py from tools/l10n/catalog/*.json (docs/L10N.md); do not edit."

# Where code names ids: GDScript L10n.t("id"...) / L10n.has("id"); C++ OpenBFMEText::text("id"...).
SCAN_GD = (REPO / "launcher/scripts", REPO / "godot/scripts")
SCAN_CPP = (REPO / "engine/src",)
GD_USE = re.compile(r"""\bL10n\.(?:t|has)\(\s*["']([^"']+)["']""")
CPP_USE = re.compile(r"""\bOpenBFMEText::text\(\s*(?:[A-Za-z_][\w.:()]*|"[^"]*")\s*,\s*"([^"]+)\"""")  # (language, id, ...)


# ---- placeholders -------------------------------------------------------------------------------------------------------------

PLACEHOLDER = re.compile(r"\{\{|\}\}|\{([a-z_][a-z0-9_]*)(?::(d|\.[0-3]f))?\}|[{}]")


def placeholders(text: str) -> dict[str, str]:
    """{name: type} of a message ('' = text, 'd' = integer, '.Nf' = fixed decimals); ValueError on a malformed brace."""
    found: dict[str, str] = {}
    for m in PLACEHOLDER.finditer(text):
        token = m.group(0)
        if token in ("{{", "}}"):
            continue
        if m.group(1) is None:
            raise ValueError(f"stray '{token}' at {m.start()} (write {{{{ or }}}} for a literal brace)")
        name, kind = m.group(1), m.group(2) or ""
        if found.get(name, kind) != kind:
            raise ValueError(f"{{{name}}} is used with two types")
        found[name] = kind
    return found


def message_placeholders(value) -> dict[str, str]:
    if isinstance(value, str):
        return placeholders(value)
    merged: dict[str, str] = {}
    for form in value.values():
        for name, kind in placeholders(form).items():
            if merged.get(name, kind) != kind:
                raise ValueError(f"{{{name}}} is used with two types")
            merged[name] = kind
    return merged


# ---- catalog ------------------------------------------------------------------------------------------------------------------

def load(path: Path) -> dict:
    with path.open(encoding="utf-8") as f:
        return json.load(f, object_pairs_hook=_no_duplicates)


def _no_duplicates(pairs):
    seen = {}
    for k, v in pairs:
        if k in seen:
            raise ValueError(f"duplicate key {k!r}")
        seen[k] = v
    return seen


def languages(catalog: Path = CATALOG) -> dict[str, dict]:
    return {p.stem: load(p) for p in sorted(catalog.glob("*.json"))}


def messages(data: dict) -> dict:
    return {k: v for k, v in data.items() if not k.startswith("@")}


def validate(langs: dict[str, dict]) -> list[str]:
    problems: list[str] = []
    if SOURCE not in langs:
        return [f"tools/l10n/catalog/{SOURCE}.json is missing"]
    src = messages(langs[SOURCE])
    src_types: dict[str, dict[str, str]] = {}
    for code, data in sorted(langs.items(), key=lambda kv: kv[0] != SOURCE):
        where = f"tools/l10n/catalog/{code}.json"
        if code not in PLURAL_CATEGORIES:
            problems.append(f"{where}: no plural rule for '{code}' (add it to PLURAL_CATEGORIES and the runtimes)")
            continue
        if data.get("@@locale") != code:
            problems.append(f"{where}: @@locale must be '{code}'")
        if not isinstance(data.get("@@name"), str) or not data["@@name"].strip():
            problems.append(f"{where}: @@name (the language's own name) is missing")
        status = data.get("@@status")
        if status not in STATUSES or (status == "source") != (code == SOURCE):
            problems.append(f"{where}: @@status must be 'source' for {SOURCE} and one of complete/partial/sample otherwise")
        for key, value in data.items():
            if key.startswith("@@"):
                if key not in ("@@locale", "@@name", "@@status"):
                    problems.append(f"{where}: unknown metadata {key}")
                continue
            if key.startswith("@"):
                if code != SOURCE or key[1:] not in src or not isinstance(value, dict) or set(value) != {"description"}:
                    problems.append(f"{where}: {key}: notes are {{\"description\": ...}} on an id of {SOURCE}.json")
                continue
            if not ID.fullmatch(key):
                problems.append(f"{where}: bad id '{key}' (lower-case dotted, e.g. launcher.settings.title)")
                continue
            if code != SOURCE and key not in src:
                problems.append(f"{where}: {key} is not an id of {SOURCE}.json")
                continue
            if isinstance(value, dict):
                cats = PLURAL_CATEGORIES[code]
                if set(value) != set(cats) or not all(isinstance(v, str) for v in value.values()):
                    problems.append(f"{where}: {key}: a plural message has exactly the forms {list(cats)}")
                    continue
                if code != SOURCE and not isinstance(src[key], dict):
                    problems.append(f"{where}: {key}: plural here but not in {SOURCE}.json")
                    continue
            elif not isinstance(value, str):
                problems.append(f"{where}: {key}: a message is a string or a plural object")
                continue
            elif code != SOURCE and isinstance(src[key], dict):
                problems.append(f"{where}: {key}: {SOURCE}.json has a plural message here")
                continue
            try:
                types = message_placeholders(value)
            except ValueError as e:
                problems.append(f"{where}: {key}: {e}")
                continue
            if isinstance(value, dict) and types.get("count", "d") != "d":
                problems.append(f"{where}: {key}: a plural's {{count}} is an integer ({{count:d}})")
            if code == SOURCE:
                src_types[key] = types
            elif key in src_types:
                want = dict(src_types[key])
                got = dict(types)
                if isinstance(value, dict):
                    want.pop("count", None)
                    got.pop("count", None)
                if want != got:
                    problems.append(f"{where}: {key}: placeholders {sorted(got.items())} differ from {SOURCE}'s {sorted(want.items())}")
    return problems


# ---- generation ---------------------------------------------------------------------------------------------------------------

def subset(data: dict, prefixes: tuple[str, ...]) -> dict:
    return {k: v for k, v in sorted(messages(data).items()) if k.startswith(prefixes)}


def gd_catalog(langs: dict[str, dict], prefixes: tuple[str, ...]) -> str:
    meta = {c: {"name": d["@@name"], "status": d["@@status"]} for c, d in langs.items()}
    text = {c: subset(d, prefixes) for c, d in langs.items()}
    out = [f"## {GENERATED}", "extends RefCounted", "",
           "const LANGUAGES := " + json.dumps(meta, ensure_ascii=False, sort_keys=True), "", "const TEXT := {"]
    for code in sorted(text):
        out.append(f"\t{json.dumps(code)}: {{")
        for key, value in text[code].items():
            out.append(f"\t\t{json.dumps(key)}: {json.dumps(value, ensure_ascii=False, sort_keys=True)},")
        out.append("\t},")
    out.append("}")
    return "\n".join(out) + "\n"


def _cpp_string(s: str) -> str:
    """a plain C++ literal of the UTF-8 bytes (octal escapes outside printable ASCII: no source-encoding dependence)"""
    out = []
    for b in s.encode("utf-8"):
        ch = chr(b)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= b < 0x7F and ch != "?":
            out.append(ch)
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def cpp_catalog(langs: dict[str, dict], prefixes: tuple[str, ...]) -> str:
    """X-macro rows: OPENBFME_LANGUAGE(code, name, status) and OPENBFME_TEXT(lang, id, form, text); form is "" for a plain
    message and the CLDR category for a plural form."""
    out = [f"// {GENERATED}", "// Included by OpenBFMEText.cpp with OPENBFME_LANGUAGE / OPENBFME_TEXT defined.", ""]
    for code in sorted(langs):
        d = langs[code]
        out.append(f"OPENBFME_LANGUAGE({_cpp_string(code)}, {_cpp_string(d['@@name'])}, {_cpp_string(d['@@status'])})")
    for code in sorted(langs):
        for key, value in subset(langs[code], prefixes).items():
            forms = [("", value)] if isinstance(value, str) else sorted(value.items())
            for form, text in forms:
                out.append(f"OPENBFME_TEXT({_cpp_string(code)}, {_cpp_string(key)}, {_cpp_string(form)}, {_cpp_string(text)})")
    return "\n".join(out) + "\n"


def runtime_copy() -> str:
    return RUNTIME.read_text(encoding="utf-8")


def generated(langs: dict[str, dict]) -> dict[Path, str]:
    files = {}
    for name, (prefixes, path) in CONSUMERS.items():
        files[path] = cpp_catalog(langs, prefixes) if path.suffix == ".inc" else gd_catalog(langs, prefixes)
    files[RUNTIME_COPY] = runtime_copy()
    return files


def stale_generated(langs: dict[str, dict]) -> list[str]:
    out = []
    for path, text in generated(langs).items():
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            out.append(f"{path.relative_to(REPO)} is stale: run python3 tools/l10n/l10n.py generate")
    return out


# ---- id usage -----------------------------------------------------------------------------------------------------------------

def _files(roots, suffixes):
    for root in roots:
        for p in sorted(root.rglob("*")):
            if p.suffix in suffixes and p.is_file() and p not in (RUNTIME, RUNTIME_COPY) and p.name != "catalog.gd":
                yield p


def _rel(path: Path) -> str:
    return path.relative_to(REPO).as_posix() if path.is_relative_to(REPO) else str(path)


def _call_args(text: str, start: int) -> str:
    """the argument text of the call whose '(' is at text[start] (strings and nesting respected)"""
    depth, i, quote = 0, start, ""
    while i < len(text):
        ch = text[i]
        if quote:
            if ch == "\\":
                i += 2
                continue
            if ch == quote:
                quote = ""
        elif ch in "\"'":
            quote = ch
        elif ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
            if depth == 0:
                return text[start + 1:i]
        i += 1
    return text[start + 1:]


# a catalog id written as a plain string (a table of ids, L10n.t(row[1])): counts as a use and must exist
ID_LITERAL = re.compile(r"(?:launcher|game|engine)\.[a-z0-9_]+\.[a-z0-9_.]+|common\.[a-z0-9_]+")
GD_ARG_KEYS = re.compile(r"""^\s*["'][^"']+["']\s*,\s*\{(.*)\}\s*$""", re.S)
GD_KEY = re.compile(r"""["']([a-z_][a-z0-9_]*)["']\s*:""")


def _top_level_keys(body: str) -> set[str]:
    keys, depth, quote, i = set(), 0, "", 0
    while i < len(body):
        ch = body[i]
        if quote:
            if ch == "\\":
                i += 2
                continue
            if ch == quote:
                quote = ""
        elif ch in "\"'":
            if depth == 0:
                m = GD_KEY.match(body, i)
                if m:
                    keys.add(m.group(1))
                    i = m.end()
                    continue
            quote = ch
        elif ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        i += 1
    return keys


def usage(langs: dict[str, dict], gd_roots=SCAN_GD, cpp_roots=SCAN_CPP) -> tuple[dict[str, list[str]], list[str]]:
    """{id: [file:line, ...]} the code uses, and the problems: an unknown id, or a call whose literal argument dictionary
    does not name exactly the message's placeholders (count included for a plural)."""
    src = messages(langs[SOURCE])
    used: dict[str, list[str]] = {}
    problems = []
    for pattern, roots, suffixes in ((GD_USE, gd_roots, {".gd"}), (CPP_USE, cpp_roots, {".cpp", ".h"})):
        for path in _files(roots, suffixes):
            text = path.read_text(encoding="utf-8")
            for m in pattern.finditer(text):
                key = m.group(1)
                line = text.count("\n", 0, m.start()) + 1
                where = f"{_rel(path)}:{line}"
                used.setdefault(key, []).append(where)
                if key not in src:
                    problems.append(f"{where}: unknown text id '{key}' (add it to tools/l10n/catalog/{SOURCE}.json)")
                    continue
                if pattern is not GD_USE or not m.group(0).startswith("L10n.t("):
                    continue
                args = _call_args(text, text.index("(", m.start()))
                want = set(message_placeholders(src[key]))
                if isinstance(src[key], dict):
                    want.add("count")
                dm = GD_ARG_KEYS.match(args)
                if dm:
                    got = _top_level_keys(dm.group(1))
                    if got != want:
                        problems.append(f"{where}: {key} needs the arguments {sorted(want)}, the call passes {sorted(got)}")
                elif args.strip().startswith(("\"", "'")) and "," not in args and want:
                    problems.append(f"{where}: {key} needs the arguments {sorted(want)}, the call passes none")
            if pattern is GD_USE:
                calls = {m.start(1) - 1 for m in pattern.finditer(text)}
                for kind, value, off in gd_tokens(text):
                    if kind == "str" and off not in calls and ID_LITERAL.fullmatch(value):
                        where = f"{_rel(path)}:{text.count(chr(10), 0, off) + 1}"
                        used.setdefault(value, []).append(where)
                        if value not in src:
                            problems.append(f"{where}: unknown text id '{value}' (add it to tools/l10n/catalog/{SOURCE}.json)")
    return used, problems


def unused(langs: dict[str, dict], used: dict[str, list[str]]) -> list[str]:
    return [f"tools/l10n/catalog/{SOURCE}.json: {k} is not used by any code (remove it)"
            for k in sorted(messages(langs[SOURCE])) if k not in used]


# ---- coverage -----------------------------------------------------------------------------------------------------------------

def coverage(langs: dict[str, dict]) -> dict[str, dict]:
    src = messages(langs[SOURCE])
    report = {}
    for code, data in sorted(langs.items()):
        if code == SOURCE:
            continue
        have = messages(data)
        missing = sorted(k for k in src if k not in have)
        report[code] = {"name": data.get("@@name"), "status": data.get("@@status"), "translated": len(src) - len(missing),
                        "total": len(src), "missing": missing}
    return report


# ---- lint: hard-coded English in launcher scripts -----------------------------------------------------------------------------

LINT_ROOTS = (REPO / "launcher/scripts",)
# Calls whose string arguments are not shown to the player: logs, asserts, string matching against program output or files.
QUIET_CALLS = {
    "print", "prints", "printerr", "printraw", "print_rich", "print_verbose", "push_error", "push_warning", "assert",
    "Log.line", "Log.scrub", "begins_with", "ends_with", "contains", "containsn", "find", "findn", "rfind", "trim_prefix",
    "trim_suffix", "replace", "split", "count", "match", "matchn", "get", "has", "erase", "set_meta", "get_meta", "has_meta",
    "L10n.t", "L10n.has", "create_from_string", "compile", "search", "search_all", "sub", "get_node", "get_node_or_null",
    "has_node", "find_child", "call", "callv", "has_method", "connect", "emit_signal", "set", "get_setting", "set_value",
    "get_value", "has_section_key", "has_section", "get_section_keys", "add_theme_color_override", "add_theme_constant_override",
    "add_theme_font_size_override", "add_theme_stylebox_override", "add_theme_font_override", "get_theme_color",
    "get_theme_constant", "get_theme_font", "get_theme_stylebox", "get_environment", "set_environment", "has_environment",
    "execute", "create_process", "execute_with_pipe", "shell_open", "open", "open_url", "load", "preload", "is_valid_ip_address",
    "get_state", "set_state", "headers.append", "request", "has_feature", "is_action_pressed", "Expression.parse",
}
# calls whose later arguments are defaults that may be shown: d.get("title", "Install the game")
DEFAULT_ARG_CALLS = {"get", "get_value", "get_state", "get_meta", "get_setting"}
WORD = re.compile(r"[A-Za-z]{2,}")
TWO_WORDS = re.compile(r"[A-Za-z]{2,}[ ,;:!?.\-']+[A-Za-z]{2,}")
ONE_WORD = re.compile(r"[A-Z][a-z]+[.!?:]?|OK|Ok")
SENTENCE = re.compile(r"(?:^|\s)[a-z]{3,}(?:\s|$|[,.;:!?])")
NOT_TEXT = re.compile(r"^(?:[a-z0-9_]+|[a-z0-9_.\-/:*?]+|res://.*|user://.*|https?://.*|[A-Za-z0-9_]+(?:\.[A-Za-z0-9_]+)+|%.*)$")
FORMAT = re.compile(r"%[-+ 0#]*\d*(?:\.\d+)?[sdifxXc%]|\{[a-z_][a-z0-9_]*(?::[^}]*)?\}")


def gd_tokens(text: str):
    """(kind, value, offset) for 'str', 'name', 'punct' tokens of a GDScript source (comments dropped)."""
    i, n = 0, len(text)
    while i < n:
        ch = text[i]
        if ch == "#":
            j = text.find("\n", i)
            i = n if j < 0 else j
            continue
        if ch in "\"'" or (ch in "&^r" and i + 1 < n and text[i + 1] in "\"'"):
            start = i
            prefix = ""
            if ch in "&^r":
                prefix = ch
                i += 1
            q = text[i]
            triple = text.startswith(q * 3, i)
            close = q * 3 if triple else q
            i += len(close)
            buf = []
            while i < n and not text.startswith(close, i):
                if text[i] == "\\" and prefix != "r":
                    buf.append(text[i:i + 2])
                    i += 2
                    continue
                if text[i] == "\n" and not triple:
                    break
                buf.append(text[i])
                i += 1
            i += len(close)
            yield ("str" if prefix in ("", "r") else "name", "".join(buf), start)
            continue
        if ch.isalpha() or ch == "_":
            j = i
            while j < n and (text[j].isalnum() or text[j] in "_"):
                j += 1
            yield ("name", text[i:j], i)
            i = j
            continue
        if ch.isspace():
            i += 1
            continue
        yield ("punct", ch, i)
        i += 1


def looks_english(s: str) -> bool:
    bare = FORMAT.sub(" ", s.replace("\\n", " ").replace("\\t", " ").replace("\\\"", "\"")).strip()
    if not WORD.search(bare) or NOT_TEXT.match(bare):
        return False
    if FORMAT.search(s) and re.search(r"(?:^|[\s\d])[A-Za-z]+(?:/[A-Za-z]+)?(?:$|\s)", bare):
        return True  # a unit or word next to a number: "%.1f MB/s", "%d min %d s"
    if not re.search(r"\s", bare) and re.search(r"[./\\_\-]", bare):
        return False  # a file name, path or identifier: original-RotWK, apt/Background.big
    if re.search(r"[/\\]", bare) and not SENTENCE.search(bare):
        return False  # a path with spaces: OpenBFME Launcher.app/Contents/MacOS/OpenBFME Launcher
    return bool(TWO_WORDS.search(bare) or ONE_WORD.fullmatch(bare))


def lint_file(path: Path) -> list[tuple[int, str]]:
    text = path.read_text(encoding="utf-8")
    hits = []
    toks = list(gd_tokens(text))
    stack: list[str] = []  # the call (or "" for a bracket that is not a call) each open bracket belongs to
    commas: list[int] = []  # the argument index inside each open bracket
    for k, (kind, value, off) in enumerate(toks):
        if kind == "punct":
            if value in "([{":
                name = ""
                if value == "(" and k > 0 and toks[k - 1][0] == "name":
                    name = toks[k - 1][1]
                    if k > 2 and toks[k - 2] == ("punct", ".", toks[k - 2][2]) and toks[k - 3][0] == "name":
                        qualified = toks[k - 3][1] + "." + name
                        name = qualified if qualified in QUIET_CALLS else name
                elif value == "[" and k > 0 and (toks[k - 1][0] == "name" or toks[k - 1][1] in ")]"):
                    name = "[]"  # a subscript: x["key"]
                stack.append(name)
                commas.append(0)
            elif value in ")]}" and stack:
                stack.pop()
                commas.pop()
            elif value == "," and commas:
                commas[-1] += 1
            continue
        if kind != "str" or not looks_english(value):
            continue
        nxt = toks[k + 1] if k + 1 < len(toks) else ("", "", 0)
        if nxt == ("punct", ":", nxt[2]) and stack and stack[-1] == "":
            continue  # a dictionary key
        if any((name in QUIET_CALLS and not (name in DEFAULT_ARG_CALLS and n > 0)) or name == "[]" for name, n in zip(stack, commas)):
            continue
        prev = toks[k - 1] if k else ("", "", 0)
        if prev[0] == "punct" and prev[1] in "=!" and k > 1 and toks[k - 2][1] in "=!":
            continue  # == / != comparison against program output
        if prev == ("name", "in", prev[2]) or nxt == ("name", "in", nxt[2]):
            continue
        hits.append((text.count("\n", 0, off) + 1, value))
    return hits


def lint(files=None) -> list[str]:
    allow = json.loads(ALLOW.read_text(encoding="utf-8")) if ALLOW.is_file() else {}
    problems = []
    seen_allow = set()
    paths = [Path(f).resolve() for f in files] if files else list(_files(LINT_ROOTS, {".gd"}))
    for path in paths:
        rel = path.relative_to(REPO).as_posix()
        allowed = {**allow.get("*", {}), **allow.get(rel, {})}
        if "*" in allowed:
            seen_allow.add((rel, "*"))
            continue
        for line, value in lint_file(path):
            if value in allowed:
                seen_allow.add(("*" if value in allow.get("*", {}) and value not in allow.get(rel, {}) else rel, value))
                continue
            problems.append(f"{rel}:{line}: hard-coded English {json.dumps(value)} (use L10n.t with an id from "
                            f"tools/l10n/catalog/{SOURCE}.json, or allow-list it with a reason in tools/l10n/lint_allow.json)")
    if not files:
        for rel, entries in allow.items():
            for value, reason in entries.items():
                if not str(reason).strip():
                    problems.append(f"tools/l10n/lint_allow.json: {rel}: {json.dumps(value)} needs a reason")
                if (rel, value) not in seen_allow:
                    problems.append(f"tools/l10n/lint_allow.json: {rel}: {json.dumps(value)} no longer occurs (remove it)")
    return problems


# ---- command line -------------------------------------------------------------------------------------------------------------

def check() -> list[str]:
    try:
        langs = languages()
    except (ValueError, json.JSONDecodeError) as e:
        return [f"tools/l10n/catalog: {e}"]
    problems = validate(langs)
    if problems:
        return problems
    used, use_problems = usage(langs)
    return stale_generated(langs) + use_problems + unused(langs, used) + lint()


def write_catalog(path: Path, data: dict) -> None:
    meta = {k: data[k] for k in ("@@locale", "@@name", "@@status") if k in data}
    rest = dict(sorted((k, v) for k, v in data.items() if k not in meta))
    path.write_text(json.dumps({**meta, **rest}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")


def add(fragment: Path) -> list[str]:
    """merges {id: English} into en.json under a lock (several editors may add at once); an id already there with other text is refused"""
    import fcntl
    new = load(fragment)
    with open(CATALOG / ".add.lock", "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        path = CATALOG / f"{SOURCE}.json"
        data = load(path)
        clash = [f"{k}: en.json has {json.dumps(data[k])}, the fragment {json.dumps(v)}" for k, v in new.items() if k in data and data[k] != v]
        if clash:
            return clash
        data.update(new)
        langs = languages()
        langs[SOURCE] = data
        problems = validate(langs)
        if problems:
            return problems
        write_catalog(path, data)
        for out, text in generated(langs).items():
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text, encoding="utf-8", newline="\n")
    return []


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else "check"
    if cmd == "add":
        problems = add(Path(argv[1]))
        print("\n".join(problems) if problems else f"added {len(load(Path(argv[1])))} ids")
        return 1 if problems else 0
    if cmd == "generate":
        langs = languages()
        problems = validate(langs)
        if problems:
            print("\n".join(problems))
            return 1
        for path, text in generated(langs).items():
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                path.write_text(text, encoding="utf-8", newline="\n")
                print(f"wrote {path.relative_to(REPO)}")
        return 0
    if cmd == "coverage":
        langs = languages()
        for code, r in coverage(langs).items():
            print(f"{code} ({r['name']}, {r['status']}): {r['translated']}/{r['total']} translated, {len(r['missing'])} missing "
                  f"(shown in English)")
            if "-v" in argv:
                for k in r["missing"]:
                    print(f"  missing {k}")
        return 0
    if cmd == "lint":
        problems = lint(argv[1:] or None)
    elif cmd == "check":
        problems = check()
    else:
        print(__doc__)
        return 2
    print("\n".join(problems) if problems else "ok")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
