#!/usr/bin/env python3
"""Regenerate the LuaJIT ABI prefixes (engine/src/Libraries/LuaJIT/prefix.h) without editing upstream source.

LuaJIT's public API (lua_*, luaL_*, luaopen_*, luaJIT_*) shares its names with the retail Lua 4 VM (openbfme_lua) that is linked
into the same library; the prefix renames LuaJIT's side at compilation. Every translation unit that includes a LuaJIT header
(the LuaJIT build itself, lua-gdextension and sol2, BfmeLuaRuntime.cpp) is compiled with the prefix first."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
sources = sorted((root / 'engine/thirdparty').glob('luajit-*/src'))
if len(sources) != 1:
    raise SystemExit(f'expected one engine/thirdparty/luajit-*/src, found {len(sources)}')
source = sources[0]
headers = ['lua.h', 'lauxlib.h', 'lualib.h', 'luaconf.h', 'luajit_rolling.h']
text = '\n'.join((source / h).read_text() for h in headers)
pattern = r'\b((?:lua|luaL|luaopen|luaJIT)_\w+)\b'
# names the headers #define (function-like API macros such as lua_pop) keep their own definitions
macros = set(re.findall(r'^\s*#\s*define\s+(\w+)', text, re.M))
# configuration hooks stay undefined so the upstream default branches run
configured = set(re.findall(r'defined\s*\(\s*(\w+)\s*\)', text))
configured.update(re.findall(r'^\s*#\s*ifn?def\s+(\w+)', text, re.M))
symbols = sorted(set(re.findall(pattern, text)) - macros - configured)
header = root / 'engine/src/Libraries/LuaJIT/prefix.h'
header.parent.mkdir(parents=True, exist_ok=True)
header.write_text('// Prefix LuaJIT identifiers so the retail Lua 4 VM can coexist. Generated by tools/luajit_prefix.py from '
                  + source.parent.name + '.\n#pragma once\n'
                  + ''.join(f'#define {s} objit_{s}\n' for s in symbols))
print(f'{header.relative_to(root)}: {len(symbols)} names')
