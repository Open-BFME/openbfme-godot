"""Issue #49: the other languages of the two base packages (original-RotWK, original-BFME2), as the All In One BFME Launcher's service lists them.

    python3 tools/release/aio_languages.py --capture <manifest dir>
        rewrites tools/release/aio_language_files.json and engine/data/retail-archives/language-archives.json from the service's
        manifests <manifest dir>/original-RotWK.raw and original-BFME2.raw (the raw JSON of
        https://bfmeladder.com/api/workshop/download?guid=<package>, aio_install.gd's request)
    python3 tools/release/aio_languages.py --check
        exit 1 when the two files disagree with each other (tools/release/test_aio.py)

A manifest file is installed for a language when its Language is ALL or names that language's code (aio_install.gd). The English files
are pinned by tools/release/aio_package_files.json (verified bytes). For every other language this records, per package, the files that
language ADDS (its lang/<Language>*.big archives, its splash screen) and the English files it DROPS (lang/English.big ... when the
language does not list them): name, MD5 and size, taken from the manifest. Only names, MD5s and sizes: no retail bytes.

Provenance: the manifests' MD5s. The German archives were checked against a retail German install (all six equal); the other languages'
bytes were not seen. Some manifest sizes are 0 (the service does not know them, e.g. every Turkish file): such a file keeps size 0 here,
which means "size not pinned" (the engine checks its MD5 only, the launcher does not offer a language with such a file for download).

The service tags RotWK's lang\\spanishpatch201.big "SP" and the rest of Spanish "ES": "SP" is read as "ES" (ALIASES).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
FILES = Path(__file__).resolve().parent / "aio_language_files.json"
ENGINE = REPO / "engine" / "data" / "retail-archives" / "language-archives.json"
PACKAGES = [("original-RotWK", "rotwk", "2.01"), ("original-BFME2", "bfme2", "1.06")]
ALIASES = {"SP": "ES"}
# the stem of each language's lang\<Language>.big
NAMES = {"DE": "German", "ES": "Spanish", "FR": "French", "IT": "Italian", "NL": "Dutch", "NO": "Norwegian", "PL": "Polish", "RU": "Russian",
         "SV": "Swedish", "TR": "Turkish", "EN": "English"}


def codes(language: str) -> set[str]:
    return {ALIASES.get(c, c) for c in language.split()}


def capture(manifests: Path) -> tuple[dict, dict]:
    files: dict = {}
    engine_langs: list = []
    for guid, game, patch in PACKAGES:
        m = json.loads((manifests / f"{guid}.raw").read_text())
        if m.get("Guid") != guid:
            raise SystemExit(f"{manifests / (guid + '.raw')} is not the manifest of {guid}")
        listed = [f for f in m["Files"] if f["Language"] not in ("", "ALL")]
        all_codes = sorted(set().union(*(codes(f["Language"]) for f in listed)) - {"EN"})
        english = [f for f in listed if "EN" in codes(f["Language"])]
        per = {}
        for code in all_codes:
            if code not in NAMES:
                raise SystemExit(f"{guid}: no language name for the code {code}")
            add = sorted(([f["Name"].replace("\\", "/"), f["Md5"], int(f["Size"])] for f in listed
                          if code in codes(f["Language"]) and "EN" not in codes(f["Language"])), key=lambda r: r[0].lower())
            drop = sorted((f["Name"].replace("\\", "/") for f in english if code not in codes(f["Language"])), key=str.lower)
            per[code] = {"name": NAMES[code], "add": add, "drop": drop}
            archives = [{"path": r[0], "md5": r[1], "size": r[2]} for r in add if r[0].lower().startswith("lang/") and r[0].lower().endswith(".big")]
            engine_langs.append({"game": game, "patch": patch, "language": NAMES[code], "code": code,
                                 "source": f"the All In One BFME Launcher service's manifest of {guid} {m.get('Version', '?')}"
                                           + (", equal to a retail German install" if code == "DE" else ""),
                                 "archives": archives})
        files[guid] = per
    engine = {
        "schema": "openbfme.retail-language-archives",
        "schemaVersion": 1,
        "note": "Generated by tools/release/aio_languages.py: do not edit. Known language archives of non-English retail installs (path, size, md5; "
                "hashes only). They replace the policies' English lang/*.big archives (the entries whose language is not ALL) when the install holds "
                "that language. A size of 0 is not pinned (the service lists it as 0): the md5 is still checked. A language that is not listed here "
                "is still mounted, with a warning (OPENBFME_STRICT_LANGUAGE=1 refuses it). The engine matches paths case-insensitively and keeps the "
                "English entries' case style, so the archives sort into the same mount order.",
        "languages": engine_langs,
    }
    return files, engine


def render_files(files: dict) -> str:
    out = ["{"]
    pkgs = []
    for guid, per in files.items():
        langs = []
        for code, d in per.items():
            add = ",\n".join("        " + json.dumps(r) for r in d["add"])
            langs.append(f'    {json.dumps(code)}: {{"name": {json.dumps(d["name"])}, "drop": {json.dumps(d["drop"])}, "add": [\n{add}\n    ]}}')
        pkgs.append(f"  {json.dumps(guid)}: {{\n" + ",\n".join(langs) + "\n  }")
    out.append(",\n".join(pkgs))
    out.append("}")
    return "\n".join(out) + "\n"


def render_engine(engine: dict) -> str:
    return json.dumps(engine, indent=2) + "\n"


def _no_duplicate_keys(pairs: list) -> dict:
    """json object_pairs_hook: a key given twice is an error (json.loads would keep the last one silently)"""
    out: dict = {}
    for k, v in pairs:
        if k in out:
            raise ValueError(f"duplicate key {k!r}")
        out[k] = v
    return out


def load() -> tuple[dict, dict]:
    return (json.loads(FILES.read_text(), object_pairs_hook=_no_duplicate_keys),
            json.loads(ENGINE.read_text(), object_pairs_hook=_no_duplicate_keys))


def check(files: dict, engine: dict) -> list[str]:
    """the engine's language archives are exactly the lang/*.big files the launcher's language table adds: every package has a table, every
    (game, language code) and every (game, language name) is listed once in the engine's file, and neither file has a language the other lacks
    (PR #77 security review: an empty table, or two engine entries of one language collapsing into one, passed before)"""
    errors = []
    if not isinstance(files, dict) or not isinstance(engine, dict):
        return ["the language tables are not JSON objects"]
    languages = engine.get("languages")
    if not isinstance(languages, list) or not languages:
        errors.append(f"{ENGINE.name} lists no languages")
        languages = []
    games = {game: patch for _, game, patch in PACKAGES}
    by_game: dict = {}
    names: set = set()
    for i, l in enumerate(languages):
        if not isinstance(l, dict) or not all(isinstance(l.get(k), str) for k in ("game", "patch", "code", "language")) \
                or not isinstance(l.get("archives"), list):
            errors.append(f"{ENGINE.name} languages[{i}] is not a {{game, patch, code, language, archives}} entry")
            continue
        key = (l["game"], l["code"])
        if l["game"] not in games or l["patch"] != games[l["game"]]:
            errors.append(f"{ENGINE.name} languages[{i}]: {l['game']} {l['patch']} is not one of the base packages")
        if NAMES.get(l["code"]) != l["language"]:
            errors.append(f"{ENGINE.name} languages[{i}]: the code {l['code']} is not the language {l['language']}")
        if key in by_game:
            errors.append(f"{ENGINE.name}: {l['game']} {l['code']} is listed twice")
        name = (l["game"], l["patch"], l["language"].lower())  # the engine's own key (RetailArchivePolicy.cpp knownLanguageArchives)
        if name in names:
            errors.append(f"{ENGINE.name}: {l['game']} {l['language']} is listed twice")
        names.add(name)
        paths = [a.get("path", "").lower() if isinstance(a, dict) else "" for a in l["archives"]]
        if len(set(paths)) != len(paths) or "" in paths:
            errors.append(f"{ENGINE.name} languages[{i}]: an archive path is missing or listed twice")
        by_game.setdefault(key, l)
    seen = set()
    for guid, game, patch in PACKAGES:
        per = files.get(guid)
        if not isinstance(per, dict) or not per:
            errors.append(f"{FILES.name} has no languages for {guid}")
            continue
        for code, d in per.items():
            seen.add((game, code))
            want = sorted(([r[0].lower(), r[1], r[2]] for r in d["add"] if r[0].lower().startswith("lang/") and r[0].lower().endswith(".big")))
            e = by_game.get((game, code))
            got = sorted(([a["path"].lower(), a["md5"], a["size"]] for a in e["archives"])) if e else None
            if got != want:
                errors.append(f"{guid} {code}: the engine's language-archives.json has {got}, {FILES.name} {want}")
    for game, code in sorted(set(by_game) - seen):
        errors.append(f"{ENGINE.name}: {game} {code} is not in {FILES.name}")
    for guid in sorted(set(files) - {g for g, _, _ in PACKAGES}):
        errors.append(f"{FILES.name}: {guid} is not a base package")
    return errors


def main(argv: list[str]) -> int:
    if argv[:1] == ["--capture"]:
        files, engine = capture(Path(argv[1]))
        FILES.write_text(render_files(files))
        ENGINE.write_text(render_engine(engine))
        print(f"wrote {FILES.relative_to(REPO)} and {ENGINE.relative_to(REPO)}")
        return 0
    if argv[:1] == ["--check"]:
        try:
            errors = check(*load())
        except ValueError as e:  # a duplicate key, or a file that is not JSON
            errors = [str(e)]
        if errors:
            print("AIO LANGUAGES DISAGREE:\n" + "\n".join(errors))
            return 1
        print("AIO LANGUAGES OK")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
