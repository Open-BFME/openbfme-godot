#!/usr/bin/env python3
"""Extract stock BFME2/RotWK wall-hub placements, preserving every map-object property.
Exact-path 2.02 equivalents receive fallbacks only when their grid dimensions match.
"""
import argparse, collections, json, os, struct, sys
from pathlib import Path
sys.path[:0] = [str(Path(__file__).parent / 'audio'), str(Path(__file__).parent / 'maps/oracle')]
from bigread import Mount, read_big


def parse_map(blob):
    import census, fullparse as f
    b, _ = census.decode(blob)
    names, start = census.parse_toc(b)
    ctx = f.Ctx(names)
    markers, dimensions = [], []
    def walk(p, end):
        while p < end:
            cid, version, size = struct.unpack_from('<IHi', b, p)
            body, finish = p + 10, p + 10 + size
            name = names[cid]
            if name == 'ObjectsList': walk(body, finish)
            elif name == 'HeightMapData':
                # Same layout as the independent oracle reader.
                r = f.R(b, body, finish)
                dimensions.extend([r.i32(), r.i32(), r.i32()])
            elif name == 'Object':
                r = f.R(b, body, finish)
                x, y, z, angle = [r.f32() for _ in range(4)]
                flags, template = r.i32(), r.astr()
                props = f.read_dict(r, ctx, 'object') if version >= 2 else {}
                if ('wallhub' in template.lower() or
                    'wallhub' in str(props.get('uniqueID', '')).lower() or
                    'wallhub' in str(props.get('GenericAIObjectName', '')).lower() or
                    'GenericAIObjectWallHubNumber' in props):
                    markers.append(dict(x=x, y=y, z=z, angle=angle, flags=flags,
                                        template=template, properties=props))
            p = finish
    walk(start, len(b))
    return dict(dimensions=dimensions, markers=markers)


def lua(value):
    if isinstance(value, dict):
        return '{' + ','.join('[' + lua(k) + ']=' + lua(v) for k, v in value.items()) + '}'
    if isinstance(value, list): return '{' + ','.join(map(lua, value)) + '}'
    if isinstance(value, str): return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool): return 'true' if value else 'false'
    return repr(value)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--rotwk', required=True)
    p.add_argument('--bfme2', required=True)
    p.add_argument('--maps-202', default='godot/mods/rotwk_202_maps.big')
    p.add_argument('--output', default='godot/data/wall_hub_markers.lua')
    a = p.parse_args()
    os.environ.update(ROTWK_INSTALL=a.rotwk, BFME2_INSTALL=a.bfme2)
    # Mount each stock game's maps independently, in the engine's normal archive precedence.
    merged = Mount(a.rotwk, a.bfme2)
    sources, candidates = {}, collections.defaultdict(list)
    for game, root in [('bfme2', a.bfme2), ('rotwk', a.rotwk)]:
        entries = {}
        for archive in merged.order:
            if Path(archive).resolve().parent != Path(root).resolve(): continue
            for name, offset, size in read_big(archive):
                if name.endswith('.map') and name.startswith('maps\\'):
                    entries.setdefault(name, (archive, offset, size))
        for name, (archive, offset, size) in sorted(entries.items()):
            with open(archive, 'rb') as stream:
                stream.seek(offset); blob = stream.read(size)
            data = parse_map(blob)
            if not data['markers']: continue
            data.update(game=game, map=name, archive=Path(archive).name)
            key = game + ':' + name
            sources[key] = data
            candidates[name].insert(0, key)  # prefer RotWK, retain BFME2 separately
    equivalents, skipped = {}, []
    with open(a.maps_202, 'rb') as stream:
        for name, offset, size in read_big(a.maps_202):
            if name not in candidates: continue
            stream.seek(offset); target = parse_map(stream.read(size))
            if target['markers']: continue  # native placements always win
            source = next((k for k in candidates[name]
                           if sources[k]['dimensions'] == target['dimensions']), None)
            if source: equivalents[name] = source
            else: skipped.append(name)
    data = dict(version=1, sources=sources, equivalents=equivalents)
    path = Path(a.output); path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('-- Generated by tools/extract_wall_hub_markers.py; SAGE coordinates, angles in radians.\nreturn ' + lua(data) + '\n')
    print(f'{len(sources)} source maps, {sum(len(v["markers"]) for v in sources.values())} markers; {len(equivalents)} compatible 2.02 maps')
    print('Dimension mismatches:', ', '.join(skipped) or 'none')

if __name__ == '__main__': main()
