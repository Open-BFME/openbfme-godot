"""Edition census (lane BFME2MODE-0, docs/EDITIONS.md): how much of the ported simulation differs between BFME2 1.06 and RotWK 2.01.

Every "RW 0x..." cite in engine/src/GameLogic and engine/src/Common is resolved to its RotWK function through the xmap
(workspace/rebuild/xmap/rw_map.csv, tools/re/README.md) and classified:

  same          tier A (identical after masking addresses), or tier B same-shape whose operand differences are layout only:
                struct field offsets and vtable slots, stack frame sizes, allocation sizes, register choice, addresses of the
                same strings / globals ("offset-only")
  divergent     a real rule difference: a same-shape pair with a changed immediate constant or a changed constant in .rdata
                (a float the code loads), a call to a different function (the callee does not map to the BFME2 callee), or
                tier B edited (instructions added / removed: branches), C or D (diverged)
  rotwk-only    no BFME2 counterpart (the expansion's code)
  unresolved    the cite is not inside a mapped function: data / field tables (.rdata), globals (.data), code outside the
                function list, or no address of the image

and, the other way round, the BFME2-only GameLogic functions: BFME2 1.06 functions with no RotWK counterpart whose decomp
source is under GameLogic (never ported, since every port starts from RotWK).

The binaries (--rotwk / --bfme2 game.dat, capstone + pefile) split tier B same-shape and check call targets; without them every
same-shape pair counts as "same-shape (unsplit)". Outputs: --json (per function detail, with disassembly: keep it under the
ignored workspace/) and --doc (replaces the generated section of docs/EDITIONS.md: counts and names only, no bytes).

  python tools/re/edition_census.py --rotwk "$ROTWK_INSTALL/game.dat" --bfme2 "$BFME2_INSTALL/game.dat" \\
      --json workspace/rebuild/xmap/edition_census.json --doc docs/EDITIONS.md
"""
