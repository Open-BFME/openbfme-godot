BASE = 0x400000
# relib.SRC_PATH (relib needs pefile): a __FILE__ literal's build-machine path
SRC_PATH = re.compile(r"^[A-Za-z]:\\.*\\([^\\]+\.(?:cpp|c|h|inl))$", re.I)
REPO = Path(__file__).resolve().parents[2]
SCAN_DIRS = ("engine/src/GameLogic", "engine/src/Common")
SUFFIXES = {".cpp", ".h", ".inc", ".hpp", ".c"}
BEGIN = "<!-- edition_census:begin (generated by tools/re/edition_census.py; do not edit by hand) -->"
END = "<!-- edition_census:end -->"

# "RW 0x85750D", chained: "RW 0x85750D -> 0x85730B", "RW 0x8AF290 .. 0x8AF2EA", "RW 0x660EC6 / 0x661869", "RW 0x1, 0x2"
CITE = re.compile(r"\bRW\s+(0x[0-9A-Fa-f]{5,8}(?:\s*(?:->|→|\.\.|/|,|-|and)\s*0x[0-9A-Fa-f]{5,8})*)")
HEXNUM = re.compile(r"0x[0-9A-Fa-f]{5,8}")
# a game-code VA (both game.dat files: image base 0x400000, code from 0x401000)
VA_MIN, VA_MAX = 0x401000, 0x1800000

LAYOUT_KINDS = {"offset", "frame", "alloc-size", "line", "register", "address", "call-unpaired"}
REAL_KINDS = {"constant", "data-constant", "call", "opcode"}
ALLOC = re.compile(r"operator new|alloc|MemoryPool|malloc|newInstance", re.I)
ECONOMY = re.compile(r"Money|Resource|Supply|Economy|Tax|CommandPoint|Bounty|Income|Cash|Treasury", re.I)


# ------------------------------------------------------------------------------------------------------------------- cites
def extract_cites(text: str) -> list[int]:
    """the RotWK VAs a source text cites ("RW 0x..." and the addresses chained to it), in order, game-code range only"""
    out = []
    for m in CITE.finditer(text):
        for h in HEXNUM.findall(m.group(1)):
            v = int(h, 16)
            if VA_MIN <= v < VA_MAX:
                out.append(v)
    return out


def scan_tree(root: Path, dirs=SCAN_DIRS) -> dict[int, set[str]]:
    """{VA: {repo-relative files citing it}} over the scanned directories"""
    cites: dict[int, set[str]] = collections.defaultdict(set)
    for d in dirs:
        for p in sorted((root / d).rglob("*")):
            if p.suffix.lower() not in SUFFIXES or not p.is_file():
                continue
            rel = p.relative_to(root).as_posix()
            for v in extract_cites(p.read_text(encoding="utf-8", errors="replace")):
                cites[v].add(rel)
    return cites


# --------------------------------------------------------------------------------------------------------------------- map
class XMap:
    def __init__(self, rows: list[dict]):
        self.rows = sorted(rows, key=lambda r: int(r["rotwk_rva"], 16))
        self.starts = [int(r["rotwk_rva"], 16) for r in self.rows]
        self.by_rva = {s: r for s, r in zip(self.starts, self.rows)}

    @classmethod
    def load(cls, path: Path) -> "XMap":
        with open(path, newline="", encoding="utf-8") as fh:
            return cls(list(csv.DictReader(fh)))

    def resolve_rva(self, rva: int) -> dict | None:
        i = bisect.bisect_right(self.starts, rva) - 1
        if i < 0:
            return None
        r = self.rows[i]
        return r if rva < self.starts[i] + int(r["size"]) else None

    def bfme2_rvas(self) -> set[int]:
        return {int(r["bfme2_rva"], 16) for r in self.rows if r["bfme2_rva"]}


def base_class(row: dict) -> str:
    """the xmap row's bucket: A, same-shape, edited, C, D or rotwk-only"""
    t, how = row["tier"], row.get("how", "")
    if t == "-":
        return "rotwk-only"
    if t == "B":
        return "same-shape" if "same-shape" in how else "edited"
    return t


def subsystem_of(row: dict) -> str:
    name = " ".join(row.get(k, "") for k in ("decomp_qualname", "decomp_source", "tu", "rotwk_name", "rtti"))
    if ECONOMY.search(name):
        return "economy"
    # "X?" is the xmap's subsystem inferred from link-order neighbours (RotWK-only code): counted under X
    return (row.get("subsystem") or "unclassified").rstrip("?")


# ------------------------------------------------------------------------------------------------- operand-level comparison
# An instruction is (mnemonic, operands, target) with operands ("reg", name) | ("imm", value) | ("mem", base, index, scale, disp, size)
# and target the absolute call / jump target (or None). `ctx` answers image questions for one side (an ImageCtx).
FRAME_REGS = {"esp", "ebp"}


class ImageCtx:
    def __init__(self, img, xmap: XMap | None = None):
        self.img, self.xmap = img, xmap

    def in_image(self, v: int) -> bool:
        return self.img.base <= v < self.img.base + self.img.size

    def section(self, v: int) -> str | None:
        return self.img.section_of(v - self.img.base)

    def string(self, v: int) -> str | None:
        return self.img.string_at(v - self.img.base)

    def value(self, v: int, size: int) -> bytes | None:
        r = v - self.img.base
        size = size if size in (4, 8, 10) else 4
        return bytes(self.img.mem[r:r + size]) if self.img.valid_rva(r + size - 1) else None

    def pointer_like(self, data: bytes | None) -> bool:
        return data is not None and len(data) >= 4 and self.in_image(struct.unpack_from("<I", data)[0])


def _address_kind(va_a: int, va_b: int, size: int, ca, cb, loads: bool) -> str:
    """two absolute addresses in the same operand: the same string / global (layout), another string literal ("constant"), or, for
    a value the instruction LOADS from .rdata (loads=True: a memory operand), a changed constant there ("data-constant": a float)"""
    sa, sb = ca.string(va_a), cb.string(va_b)
    if sa is not None and sb is not None and len(sa) >= 4 and len(sb) >= 4 and not ca.pointer_like(ca.value(va_a, 4)) and \
            not cb.pointer_like(cb.value(va_b, 4)):
        return "address" if salt(sa) == salt(sb) else "constant"
    if loads and ca.section(va_a) == ".rdata" and cb.section(va_b) == ".rdata":
        da, db = ca.value(va_a, size), cb.value(va_b, size)
        if da != db and not (ca.pointer_like(da) and cb.pointer_like(db)):
            return "data-constant"
    return "address"


def salt(s: str) -> str:
    """__FILE__ literals differ only by the build machine's path (relib.salt_string)"""
    m = SRC_PATH.match(s)
    return ("__FILE__:" + m.group(1).lower()) if m else s


def _near_file_push(ins: list, i: int, ctx) -> bool:
    """an immediate pushed next to a __FILE__ literal: the __LINE__ of an assert / allocation (layout: the source moved)"""
    for j in (i - 2, i - 1, i + 1, i + 2):
        if 0 <= j < len(ins) and ins[j][0] == "push" and ins[j][1] and ins[j][1][0][0] == "imm":
            v = ins[j][1][0][1]
            if isinstance(v, int) and ctx.in_image(v):
                t = ctx.string(v)
                if t is not None and salt(t).startswith("__FILE__:"):
                    return True
    return False


def compare_pair(a: list, b: list, ca, cb, callee_ok=None) -> tuple[set[str], list[tuple[int, str]]]:
    """kinds of difference between two instruction lists of the same shape, and (index, kind) per differing instruction.
    callee_ok(rw_target, b2_target) -> "same" | "diff" | "unpaired" judges a call's targets (None: not checked)."""
    kinds: set[str] = set()
    where: list[tuple[int, str]] = []
    if len(a) != len(b):
        return {"opcode"}, [(min(len(a), len(b)), "opcode")]
    for i, (x, y) in enumerate(zip(a, b)):
        k: set[str] = set()
        mx, ox, tx = x
        my, oy, ty = y
        if x == y:
            continue
        if mx != my or len(ox) != len(oy):
            k.add("opcode")
        elif tx is not None or ty is not None:
            if mx.startswith("call") and callee_ok is not None and tx is not None and ty is not None:
                verdict = callee_ok(tx, ty)
                if verdict != "same":
                    k.add("call" if verdict == "diff" else "call-unpaired")
        else:
            for p, q in zip(ox, oy):
                if p == q:
                    continue
                if p[0] != q[0]:
                    k.add("opcode")
                elif p[0] == "reg":
                    k.add("register")
                elif p[0] == "imm":
                    va, vb = p[1], q[1]
                    if isinstance(va, tuple) or isinstance(vb, tuple):
                        k.add("opcode")  # a branch inside the function to another place: control flow differs
                    elif ca.in_image(va) and cb.in_image(vb):
                        k.add(_address_kind(va, vb, 4, ca, cb, loads=False))
                    elif mx in ("add", "sub") and ox[0] == ("reg", "esp"):
                        k.add("frame")
                    elif mx in ("add", "sub", "imul") and ox[0][0] == "reg" and va % 4 == 0 and vb % 4 == 0:
                        k.add("offset")  # this + a field offset, an array stride (pointer arithmetic on a grown struct)
                    elif mx == "push" and _near_file_push(a, i, ca):
                        k.add("line")
                    elif mx == "push" and i + 1 < len(a) and a[i + 1][0].startswith("call") and a[i + 1][2] is not None and \
                            ca.xmap is not None and ALLOC.search(_callee_name(ca, a[i + 1][2])):
                        k.add("alloc-size")
                    else:
                        k.add("constant")
                else:  # mem
                    _, pb, pi, ps, pd, pz = p
                    _, qb, qi, qs, qd, qz = q
                    if (pb, pi, ps, pz) != (qb, qi, qs, qz):
                        k.add("register")
                    if pd != qd:
                        if pb is None and pi is None and ca.in_image(pd) and cb.in_image(qd):
                            k.add(_address_kind(pd, qd, pz, ca, cb, loads=True))
                        elif pb is None and pi is not None and ca.in_image(pd) and cb.in_image(qd):
                            k.add("address")  # a jump / lookup table
                        elif pb in FRAME_REGS:
                            k.add("frame")
                        else:
                            k.add("offset")
        for kind in sorted(k):
            where.append((i, kind))
        kinds |= k
    return kinds, where


def _callee_name(ctx, va: int) -> str:
    r = ctx.xmap.resolve_rva(va - BASE) if ctx.xmap else None
    return " ".join([r.get("decomp_qualname", ""), r.get("rotwk_name", "")]) if r else ""


def decode(img, rva: int, size: int) -> tuple[list, list[str]]:
    """(instruction tuples, listing text) of a function"""
    import capstone
    from capstone import x86

    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail = True
    out, text = [], []
    for ins in md.disasm(bytes(img.mem[rva:rva + size]), rva + img.base):
        ops, target = [], None
        is_branch = ins.mnemonic.startswith(("j", "call", "loop"))
        for op in ins.operands:
            if op.type == x86.X86_OP_REG:
                ops.append(("reg", ins.reg_name(op.reg)))
            elif op.type == x86.X86_OP_IMM:
                if is_branch:
                    target = op.imm & 0xFFFFFFFF
                    # a branch inside the function: compared by its offset from the start
                    lo = rva + img.base
                    ops.append(("imm", ("L", target - lo) if lo <= target < lo + size else ("ext",)))
                else:
                    ops.append(("imm", op.imm & 0xFFFFFFFF))
            elif op.type == x86.X86_OP_MEM:
                m = op.mem
                ops.append(("mem", ins.reg_name(m.base) if m.base else None, ins.reg_name(m.index) if m.index else None, m.scale,
                            m.disp & 0xFFFFFFFF, op.size))
        if is_branch and target is not None:
            lo = rva + img.base
            if lo <= target < lo + size:
                target = None  # internal: the ("L", offset) operand compares it
        out.append((ins.mnemonic, tuple(ops), target))
        text.append(f"{ins.mnemonic} {ins.op_str}".strip())
    return out, text


# ------------------------------------------------------------------------------------------------------------------ census
def classify_function(row: dict, rimg=None, bimg=None, xmap: XMap | None = None) -> dict:
    """{class, base, kinds, diffs}: class = same | divergent | rotwk-only (see the module doc)"""
    base = base_class(row)
    res = {"base": base, "kinds": [], "diffs": []}
    if base == "rotwk-only":
        res["class"] = "rotwk-only"
        return res
    if base in ("edited", "C", "D"):
        res["class"] = "divergent"
        res["kinds"] = ["branches" if base == "edited" else "diverged"]
        return res
    if rimg is None or bimg is None:
        res["class"] = "same" if base == "A" else "same-shape (unsplit)"
        return res
    r, rs = int(row["rotwk_rva"], 16), int(row["size"])
    b, bs = int(row["bfme2_rva"], 16), int(row["bfme2_size"])
    a_ins, a_txt = decode(rimg, r, rs)
    b_ins, b_txt = decode(bimg, b, bs)
    ca, cb = ImageCtx(rimg, xmap), ImageCtx(bimg, xmap)

    # a BFME2 function's pairing is strong when the map pairs it with a RotWK function at tier A (not ambiguous) or B
    strong_b2 = {int(x["bfme2_rva"], 16) for x in xmap.rows if x["bfme2_rva"] and (x["tier"] == "B" or (x["tier"] == "A" and
                 not x.get("how", "").startswith("amb")))} if xmap else set()

    def callee_ok(tr: int, tb: int) -> str:
        """same | diff | unpaired: the RotWK callee against the BFME2 one. "diff" only when both sides are paired by the map and the
        pairs disagree (RotWK calls another function than BFME2 does, the BFME2 callee strongly paired); a callee the map cannot
        pair, or pairs only weakly (tier C / D / ambiguous), is "unpaired"
        (a map gap, not evidence of a rule difference)"""
        cr = xmap.resolve_rva(tr - BASE)
        if cr is None:
            return "same"  # an import thunk or code outside the function list: not comparable
        b2_paired = (tb - BASE) in strong_b2
        if not cr["bfme2_rva"]:
            return "diff" if b2_paired else "unpaired"
        if int(cr["bfme2_rva"], 16) == tb - BASE:
            return "same"
        if cr["tier"] in ("C", "D") or cr.get("how", "").startswith("amb"):
            return "unpaired"  # the callee's own pairing is uncertain (README)
        return "diff" if b2_paired else "unpaired"

    kinds, where = compare_pair(a_ins, b_ins, ca, cb, callee_ok if xmap else None)
    if base == "A":
        kinds &= {"call", "call-unpaired"}  # tier A is identical after masking: only the call targets add information
        where = [w for w in where if w[1] in kinds]
    res["kinds"] = sorted(kinds)
    res["diffs"] = [{"i": i, "kind": k, "rw": a_txt[i] if i < len(a_txt) else "", "b2": b_txt[i] if i < len(b_txt) else ""}
                    for i, k in where if k in REAL_KINDS][:12]
    res["class"] = "divergent" if kinds & REAL_KINDS else "same"
    return res


def bfme2_only(xmap: XMap, bfme2_inv: list[dict], ledger: list[dict]) -> list[dict]:
    """BFME2 1.06 functions with no RotWK counterpart whose decomp source is under GameLogic"""
    import match_rotwk

    mapped = xmap.bfme2_rvas()
    src = {}
    for l in ledger:
        src.setdefault(int(l["target_rva"], 16), l)
    out = []
    for f in bfme2_inv:
        rva = int(f["rva"], 16)
        if rva in mapped:
            continue
        l = src.get(rva)
        if not l or "/GameLogic/" not in l["source"]:
            continue
        q = match_rotwk.qualname(l["name"]) or l["name"]
        out.append({"bfme2_rva": f"0x{rva:X}", "size": int(f["size"]), "qualname": q, "source": l["source"],
                    "subsystem": "economy" if ECONOMY.search(q + " " + l["source"]) else match_rotwk.path_subsystem(l["source"])})
    return out


def run(cites: dict[int, set[str]], xmap: XMap, rimg=None, bimg=None, b2only: list[dict] | None = None) -> dict:
    funcs: dict[int, dict] = {}
    unresolved: dict[str, set[int]] = collections.defaultdict(set)
    for va, files in sorted(cites.items()):
        row = xmap.resolve_rva(va - BASE)
        if row is None:
            sec = rimg.section_of(va - BASE) if rimg is not None else None
            kind = {".rdata": "data (.rdata: constants, field / lookup tables, vtables)", ".data": "globals (.data)",
                    ".text": "code outside the function list (.text)"}.get(sec, "no section" if rimg is not None else "unknown (no image)")
            unresolved[kind].add(va)
            continue
        start = int(row["rotwk_rva"], 16)
        f = funcs.setdefault(start, {"row": row, "files": set(), "cites": 0})
        f["files"] |= files
        f["cites"] += 1
    detail = []
    for start, f in sorted(funcs.items()):
        row = f["row"]
        c = classify_function(row, rimg, bimg, xmap)
        detail.append({"rotwk_rva": row["rotwk_rva"], "va": f"0x{start + BASE:X}", "bfme2_va": (f"0x{int(row['bfme2_rva'], 16) + BASE:X}" if row["bfme2_rva"] else ""),
                       "size": int(row["size"]), "tier": row["tier"], "name": row.get("decomp_qualname") or row.get("rotwk_name", ""),
                       "decomp_source": row.get("decomp_source", ""), "subsystem": subsystem_of(row), "files": sorted(f["files"]), **c})
    return {"functions": detail, "unresolved": {k: sorted(f"0x{v:X}" for v in vs) for k, vs in sorted(unresolved.items())},
            "bfme2_only": b2only or [], "cited_addresses": len(cites)}


def summarise(result: dict) -> dict:
    fn = result["functions"]
    by = collections.Counter(f["class"] for f in fn)
    base = collections.Counter((f["class"], f["base"]) for f in fn)
    kinds = collections.Counter(k for f in fn if f["class"] == "divergent" for k in f["kinds"] if k not in LAYOUT_KINDS)
    subs: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    for f in fn:
        key = f["class"] if f["class"] != "same" else ("identical" if f["base"] == "A" else "offset-only")
        subs[f["subsystem"]][key] += 1
    for f in result["bfme2_only"]:
        subs[f["subsystem"]]["bfme2-only"] += 1
    return {"functions": len(fn), "same": by["same"], "identical": base[("same", "A")], "offset_only": base[("same", "same-shape")],
            "unsplit": by["same-shape (unsplit)"], "divergent": by["divergent"], "rotwk_only": by["rotwk-only"],
            "bfme2_only": len(result["bfme2_only"]), "divergent_kinds": dict(sorted(kinds.items())),
            "divergent_bases": {b: n for (c, b), n in sorted(base.items()) if c == "divergent"},
            "unresolved": {k: len(v) for k, v in result["unresolved"].items()}, "cited_addresses": result["cited_addresses"],
            "subsystems": {k: dict(v) for k, v in sorted(subs.items())}}


# --------------------------------------------------------------------------------------------------------------------- doc
def render(summary: dict, result: dict, inputs: dict) -> str:
    s = summary
    L = [BEGIN, "", f"Inputs: {inputs.get('text', '')}", ""]
    L += ["| Class | Functions | Meaning |", "|---|---|---|",
          f"| same behaviour | {s['same']} | tier A identical {s['identical']} + tier B same-shape with layout-only differences {s['offset_only']} |",
          f"| real divergence | {s['divergent']} | " + ", ".join(f"{k} {v}" for k, v in s["divergent_kinds"].items()) + " |",
          f"| RotWK-only | {s['rotwk_only']} | no BFME2 counterpart: off in the BFME2 edition |",
          f"| BFME2-only GameLogic | {s['bfme2_only']} | BFME2 functions with no RotWK counterpart, never ported |"]
    if s["unsplit"]:
        L.append(f"| same-shape (unsplit) | {s['unsplit']} | not split: the census ran without the binaries |")
    L += ["", f"{s['functions']} RotWK functions are cited from {s['cited_addresses']} distinct addresses in engine/src/GameLogic and "
          "engine/src/Common. A function counts once, in the first class that applies (divergent if any difference is real).", "",
          "Unresolved cites (the address is not inside a mapped function):", ""]
    L += [f"- {k}: {v}" for k, v in s["unresolved"].items()]
    L += ["", "Per subsystem (the xmap's subsystem of the RotWK function; \"economy\" = money, resources, supply, command points, taxes):", "",
          "| Subsystem | Identical | Offset-only | Real divergence | RotWK-only | BFME2-only GameLogic |", "|---|---|---|---|---|---|"]
    for sub, c in sorted(s["subsystems"].items(), key=lambda kv: -sum(kv[1].values())):
        L.append(f"| {sub} | {c.get('identical', 0)} | {c.get('offset-only', 0)} | {c.get('divergent', 0)} | {c.get('rotwk-only', 0)} | {c.get('bfme2-only', 0)} |")
    tot = collections.Counter()
    for c in s["subsystems"].values():
        tot.update(c)
    L.append(f"| **total** | {tot.get('identical', 0)} | {tot.get('offset-only', 0)} | {tot.get('divergent', 0)} | {tot.get('rotwk-only', 0)} | {tot.get('bfme2-only', 0)} |")
    # the BFME2-only GameLogic functions, by class
    by_class: dict[str, list[str]] = collections.defaultdict(list)
    for f in result["bfme2_only"]:
        q = f["qualname"]
        cls = q.rsplit("::", 1)[0] if "::" in q else "(free functions)"
        by_class[cls].append(q.rsplit("::", 1)[-1])
    L += ["", f"<details><summary>The {s['bfme2_only']} BFME2-only GameLogic functions, by class</summary>", ""]
    for cls, names in sorted(by_class.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        L.append(f"- `{cls}` ({len(names)}): " + ", ".join(f"`{n}`" for n in sorted(set(names))[:40]) + (" ..." if len(set(names)) > 40 else ""))
    L += ["", "</details>", "", END]
    return "\n".join(L)


def replace_section(doc: str, section: str) -> str:
    if BEGIN not in doc or END not in doc:
        raise SystemExit("docs/EDITIONS.md has no generated census section (the begin / end markers)")
    head, rest = doc.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + section + tail


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--map", help="rw_map.csv (default: the main checkout's workspace/rebuild/xmap/rw_map.csv)")
    ap.add_argument("--bfme2-inv", help="bfme2_functions.csv (default: next to the map)")
    ap.add_argument("--ledger", help="bfme2_ledger.csv (default: next to the map)")
    ap.add_argument("--rotwk", help="RotWK 2.01 game.dat")
    ap.add_argument("--bfme2", help="BFME2 1.06 game.dat")
    ap.add_argument("--src", default=str(REPO), help="the checkout whose engine/src is scanned")
    ap.add_argument("--json")
    ap.add_argument("--doc")
    args = ap.parse_args(argv)
    import rw2decomp

    mp = Path(args.map) if args.map else rw2decomp.main_checkout() / "workspace/rebuild/xmap/rw_map.csv"
    xmap = XMap.load(mp)
    inv = Path(args.bfme2_inv) if args.bfme2_inv else mp.parent / "bfme2_functions.csv"
    led = Path(args.ledger) if args.ledger else mp.parent / "bfme2_ledger.csv"
    with open(inv, newline="", encoding="utf-8") as fh:
        bfme2_inv = list(csv.DictReader(fh))
    with open(led, newline="", encoding="utf-8") as fh:
        ledger = list(csv.DictReader(fh))
    rimg = bimg = None
    if args.rotwk and args.bfme2:
        import relib

        rimg, bimg = relib.Image(args.rotwk), relib.Image(args.bfme2)
    cites = scan_tree(Path(args.src))
    result = run(cites, xmap, rimg, bimg, bfme2_only(xmap, bfme2_inv, ledger))
    summary = summarise(result)
    src_sha = subprocess.run(["git", "-C", args.src, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    inputs = {"text": f"engine source {src_sha}; xmap {mp.name} ({len(xmap.rows)} RotWK functions); BFME2 inventory {len(bfme2_inv)} functions, "
                      f"decomp ledger {len(ledger)} rows; binaries " + (f"RotWK md5 {rimg.md5}, BFME2 md5 {bimg.md5}" if rimg else "not given")}
    print(json.dumps(summary, indent=1))
    if args.json:
        Path(args.json).write_text(json.dumps({"summary": summary, "inputs": inputs, **result}, indent=1), encoding="utf-8")
    if args.doc:
        p = Path(args.doc)
        p.write_text(replace_section(p.read_text(encoding="utf-8"), render(summary, result, inputs)), encoding="utf-8")


if __name__ == "__main__":
    main()
