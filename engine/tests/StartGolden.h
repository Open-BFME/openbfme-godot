struct Spec
{
	int slot;
	bool observer = false;
	int tmpl = -1, color = -1, start = -1, team = -1;
};
inline std::vector<Spec> scenario(const std::string &name)
{
	if (name == "two")
	{
		return { { 0 }, { 1 } };
	}
	if (name == "four_teams")
	{
		return { { 0, false, -1, -1, -1, 0 }, { 1, false, -1, -1, -1, 1 }, { 2, false, -1, -1, -1, 0 }, { 3, false, -1, -1, -1, 1 } };
	}
	if (name == "eight")
	{
		std::vector<Spec> v;
		for (int i = 0; i < 8; ++i)
		{
			v.push_back({ i, false, -1, -1, -1, i % 2 });
		}
		return v;
	}
	if (name == "mixed")
	{
		return { { 0, false, 5, 2, 3, -1 }, { 1 }, { 2, false, 3, -1, -1, 1 }, { 3, false, -1, 2, -1, -1 } };
	}
	if (name == "observer")
	{
		return { { 0 }, { 1 }, { 2, true, -2 } };
	}
	return {};
}

inline SkirmishGameInfo makeInfo(const std::vector<Spec> &specs)
{
	SkirmishGameInfo g;
	for (const Spec &s : specs)
	{
		SkirmishGameSlot &slot = g.slots[s.slot];
		slot.state = s.slot == 0 ? SLOT_PLAYER : SLOT_EASY_AI;
		slot.name = u"p" + std::u16string(1, (char16_t)(u'0' + s.slot));
		slot.accepted = true;
		slot.playerTemplate = s.observer ? PLAYERTEMPLATE_OBSERVER : s.tmpl;
		slot.color = s.color;
		slot.startPos = s.start;
		slot.teamNumber = s.team;
	}
	return g;
}

