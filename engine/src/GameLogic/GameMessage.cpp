const char *GameMessageTypeName(int type)
{
	if (type == MSG_BEGIN_NETWORK_MESSAGES)
	{
		return "MSG_BEGIN_NETWORK_MESSAGES";
	}
	if (type >= 1001 && type <= 1147)
	{
		return kLogicMessageNames[type - 1001];
	}
	return "";
}
