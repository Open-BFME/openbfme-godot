const char *W3D_Chunk_Name(std::uint32_t id)
{
	const ChunkName *end = kChunkNames + kChunkNameCount;
	const ChunkName *it = std::lower_bound(kChunkNames, end, id, [](const ChunkName &c, std::uint32_t v) { return c.Id < v; });
	return (it != end && it->Id == id) ? it->Name : nullptr;
}

std::vector<std::uint32_t> W3D_Chunk_All_Ids()
{
	std::vector<std::uint32_t> ids;
	for (const ChunkName &c : kChunkNames)
	{
		ids.push_back(c.Id);
	}
	return ids;
}

void W3DChunkWalkStats::Merge(const W3DChunkWalkStats &other)
{
	for (const auto &kv : other.ById)
	{
		W3DChunkStat &s = ById[kv.first];
		s.Count += kv.second.Count;
		s.Bytes += kv.second.Bytes;
	}
	for (const auto &kv : other.ByParent)
	{
		ByParent[kv.first] += kv.second;
	}
	Unknown.insert(Unknown.end(), other.Unknown.begin(), other.Unknown.end());
}

bool Walk_W3D_Chunks(const std::uint8_t *data, size_t size, W3DChunkWalkStats &stats, std::string *error)
{
	ChunkLoadClass cload(data, size);
	walk(cload, W3DChunkWalkStats::ROOT, stats);
	if (cload.Had_Error())
	{
		if (error)
		{
			*error = "a chunk overruns its parent or the file, or a partial chunk header trails";
		}
		return false;
	}
	return true;
}
