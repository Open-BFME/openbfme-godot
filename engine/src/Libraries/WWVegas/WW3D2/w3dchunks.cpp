const size_t kChunkNameCount = sizeof(kChunkNames) / sizeof(kChunkNames[0]);

void walk(ChunkLoadClass &cload, std::uint32_t parent, W3DChunkWalkStats &stats)
{
	while (cload.Open_Chunk())
	{
		std::uint32_t id = cload.Cur_Chunk_ID();
		std::uint32_t size = cload.Cur_Chunk_Length();
		W3DChunkStat &stat = stats.ById[id];
		stat.Count++;
		stat.Bytes += size;
		stats.ByParent[std::make_pair(parent, id)]++;
		if (!W3D_Chunk_Is_Known(id))
		{
			stats.Unknown.push_back(id);
		}
		if (cload.Contains_Chunks())
		{
			walk(cload, id, stats);
		}
		cload.Close_Chunk();
	}
}

